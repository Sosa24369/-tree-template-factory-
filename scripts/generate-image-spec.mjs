/**
 * docs/IMAGE-SPEC.md — generated from app/src/templates/imageSlots.mjs.
 *
 * The contract lives in one file and this renders it as the tables a client can be
 * handed: one per template, one row per slot, exact pixels. Never edit the .md by
 * hand; edit the contract and run `node scripts/generate-image-spec.mjs`.
 */
import { writeFileSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { BREAKPOINTS, MASTERS, SHARED_SLOTS, IMAGE_SLOTS } from '../app/src/templates/imageSlots.mjs';

const ROOT = new URL('..', import.meta.url).pathname;
// TEMPLATE_META is TypeScript (templates/meta.ts, data only); read the id + label
// pairs out of it the way generate-lead-registry.mjs does.
const META_TS = readFileSync(join(ROOT, 'app', 'src', 'templates', 'meta.ts'), 'utf8');
const TEMPLATE_META = [...META_TS.matchAll(/\{\s*id:\s*'([^']+)',\s*label:\s*'([^']+)'/g)].map((m) => ({ id: m[1], label: m[2] }));
if (TEMPLATE_META.length !== 10) throw new Error(`expected 10 templates in meta.ts, found ${TEMPLATE_META.length}`);

const ratio = ([w, h]) => {
  const r = w / h;
  if (Math.abs(r - 4 / 3) < 0.03) return '4:3';
  if (Math.abs(r - 3 / 4) < 0.03) return '3:4';
  if (Math.abs(r - 1) < 0.03) return '1:1';
  if (Math.abs(r - 16 / 9) < 0.03) return '16:9';
  return r >= 1 ? `${r.toFixed(2)}:1` : `1:${(1 / r).toFixed(2)}`;
};
const uniq = (arr) => [...new Set(arr)];
const renders = (list) => {
  if (!list) return '—';
  const cells = uniq(list.map(([w, h]) => `${w} × ${h}`));
  return cells.join(', ');
};
const aspects = (slot) => {
  if (slot.policy === 'frame') return `master (${MASTERS[slot.master].aspect.join(':')})`;
  if (slot.policy === 'contain') return '1:1 canvas';
  const per = BREAKPOINTS.map((b) => slot.renders[b.id] ? uniq(slot.renders[b.id].map(ratio)).join('/') : '—');
  return uniq(per).length === 1 ? per[0] : per.join(' · ');
};
const upload = (slot) => {
  const m = MASTERS[slot.master];
  if (slot.master === 'logo') return m.recommended;
  return `${m.recommended[0]} × ${m.recommended[1]}, ${m.aspect.join(':')} (or larger)`;
};
const minimum = (slot) => {
  const m = MASTERS[slot.master];
  if (slot.master === 'logo') return `${m.min} px longest edge`;
  return `${m.min[0]} × ${m.min[1]}`;
};
const policy = (slot) => ({ cover: 'cover — crops, needs a focal point', frame: 'frame — the whole photo, in the master\'s shape', contain: 'contain — never cropped', plate: 'plate — decorative, under a tint' })[slot.policy];

const lines = [];
lines.push('# Image spec — every image slot on every template');
lines.push('');
lines.push('<!-- GENERATED by scripts/generate-image-spec.mjs from app/src/templates/imageSlots.mjs. Do not edit by hand. -->');
lines.push('');
lines.push('Hand this to a client. Every number is a measured render size in CSS pixels at the three');
lines.push(`viewports the pages were measured at (${BREAKPOINTS.map((b) => `${b.label.toLowerCase()} ${b.viewport}`).join(', ')}); screens draw at 2× that, which is where the minimums come from.`);
lines.push('');
lines.push('## What to send');
lines.push('');
lines.push('| Kind | Send | Minimum | Why |');
lines.push('|---|---|---|---|');
lines.push(`| Job photographs | **${MASTERS.photo.recommended[0]} × ${MASTERS.photo.recommended[1]} px, 4:3**, JPEG or PNG. Landscape. One subject per photo — no before/after composites (they get cut through the middle in the wide slots) | ${MASTERS.photo.min[0]} × ${MASTERS.photo.min[1]} | ${MASTERS.photo.why} |`);
lines.push(`| The lead removal photo (removal-a hero) | **${MASTERS.heroPlate.recommended[0]} × ${MASTERS.heroPlate.recommended[1]} px or larger, 4:3**. Quiet background; the headline sits on it | ${MASTERS.heroPlate.min[0]} × ${MASTERS.heroPlate.min[1]} | ${MASTERS.heroPlate.why} |`);
lines.push(`| Logo | **${MASTERS.logo.recommended}**. No white box baked in, no phone number in the artwork | ${MASTERS.logo.min} px | ${MASTERS.logo.why} |`);
lines.push(`| Section backgrounds (optional) | ${MASTERS.art.recommended[0]} × ${MASTERS.art.recommended[1]} px, 16:9. Texture, not detail — they sit under a heavy tint | ${MASTERS.art.min[0]} × ${MASTERS.art.min[1]} | ${MASTERS.art.why} |`);
lines.push('');
lines.push('iPhone HEIC files are refused with a message; export as JPEG or PNG first. Every upload is');
lines.push('auto-rotated, stripped of metadata, cropped to 4:3 around the focal point you click, and');
lines.push('re-encoded as WebP at 400 / 800 / 1200 / 1600 px wide. The original is never published.');
lines.push('');
lines.push('## How photos reach the slots');
lines.push('');
lines.push('A client uploads **sets**, one per service (removal, trimming, storm, generic). A template');
lines.push('picks from its service\'s set **by position** — the first removal photo is removal-a\'s hero');
lines.push('plate, the last three are its service strip — so reordering a set re-slots the photos. A');
lines.push('service with no photos falls back within the client (removal → generic → storm → trimming),');
lines.push('never to another client\'s photographs and never to template artwork.');
lines.push('');
lines.push('Policies: **cover** slots have a fixed box and crop the photo to fill it — the focal point');
lines.push('you click decides what survives the crop. **frame** slots show the whole photo in its own');
lines.push('shape, so a grid of them is only even when every photo is the same shape (4:3).');
lines.push('**contain** never crops (logos). **plate** is a decorative background under a tint.');
lines.push('');
lines.push('## Every template: the logo');
lines.push('');
lines.push('| Slot | Where | Mobile | Tablet | Desktop | Policy | Send | Minimum | Notes |');
lines.push('|---|---|---|---|---|---|---|---|---|');
for (const s of SHARED_SLOTS) lines.push(`| **${s.label}** | ${s.section} | ${renders(s.renders.mobile)} | ${renders(s.renders.tablet)} | ${renders(s.renders.desktop)} | ${policy(s)} | ${upload(s)} | ${minimum(s)} | ${s.notes ?? ''} |`);
lines.push('');
for (const t of TEMPLATE_META) {
  const slots = IMAGE_SLOTS.filter((s) => s.template === t.id);
  if (!slots.length) continue;
  lines.push(`## ${t.label} (\`${t.id}\`)`);
  lines.push('');
  lines.push('| Slot | Fed by | Mobile | Tablet | Desktop | Aspect | Policy | Focal point | Send | Minimum | Notes |');
  lines.push('|---|---|---|---|---|---|---|---|---|---|---|');
  for (const s of slots) {
    const fed = s.source.set === 'art' ? `background plate \`${s.source.pick}\`` : `\`photos.${s.source.set}\` — ${s.source.pick}`;
    lines.push(`| **${s.label}** | ${fed} | ${renders(s.renders.mobile)} | ${renders(s.renders.tablet)} | ${renders(s.renders.desktop)} | ${aspects(s)} | ${policy(s)} | ${s.focal}${s.legibility ? ' · headline sits on it' : ''} | ${upload(s)} | ${minimum(s)} | ${s.notes ?? ''} |`);
  }
  lines.push('');
}
lines.push('---');
lines.push('');
lines.push(`Measured ${new Date().toISOString().slice(0, 10)} with headless Chrome over the DevTools protocol against the built pages; ${IMAGE_SLOTS.length} slots across ${TEMPLATE_META.length} templates plus the two shared logo slots.`);
writeFileSync(join(ROOT, 'docs', 'IMAGE-SPEC.md'), lines.join('\n') + '\n');
console.log(`docs/IMAGE-SPEC.md: ${IMAGE_SLOTS.length + SHARED_SLOTS.length} rows`);
